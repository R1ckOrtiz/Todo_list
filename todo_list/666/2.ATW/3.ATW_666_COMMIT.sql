-- Incluir/Reativar 'NFMK30' na ELEMENT_AREA_OPERACIONAL
MERGE INTO ELEMENT_AREA_OPERACIONAL T
USING (
    SELECT E.EM_ID_EM, AO.AO_ID_AO
    FROM ELEMENT E
    JOIN AREA_OPERACIONAL AO ON AO.AO_COD_AOP = 'NFM-NAN'
    WHERE E.EM_COD_EM = 'NFMK30'
      AND E.EM_IND_ELE = 'Y'
) S
ON (T.EM_ID_EM = S.EM_ID_EM)
WHEN MATCHED THEN
    UPDATE SET T.AO_ID_AO = S.AO_ID_AO
WHEN NOT MATCHED THEN
    INSERT (EM_ID_EM, AO_ID_AO)
    VALUES (S.EM_ID_EM, S.AO_ID_AO);

-- Incluir/Reativar 'NFMK30' na SBS_AREA_OPERACIONAL_TL
MERGE INTO SBS_AREA_OPERACIONAL_TL T
USING (
    SELECT 'NFMK30' AS EM_COD_EM,
           AO_PC.AO_ID_AO AS AO_ID_AO_TL,
           AO_MAE.AO_ID_AO AS AO_ID_AO_MAE_TL
    FROM AREA_OPERACIONAL AO_PC
    JOIN AREA_OPERACIONAL AO_MAE ON AO_MAE.AO_COD_AOP = 'NFM'
    WHERE AO_PC.AO_COD_AOP = 'NFM-NAN'
) S
ON (T.EM_COD_EM = S.EM_COD_EM)
WHEN MATCHED THEN
    UPDATE SET
        T.AO_ID_AO_TL = S.AO_ID_AO_TL,
        T.AO_ID_AO_MAE_TL = S.AO_ID_AO_MAE_TL
